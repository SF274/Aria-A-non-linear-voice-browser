/** SPEC 5.15: constant, always present, so unrelated listeners can cheaply ignore our messages. */
export const ENVELOPE_NS = "echo";

/** SPEC 5.15. */
export const ENVELOPE_TARGETS = ["sw", "content", "offscreen"] as const;

export const EnvelopeTargetSchema = z.enum(ENVELOPE_TARGETS);

export type EnvelopeTarget = z.infer<typeof EnvelopeTargetSchema>;

/**
 * SPEC 5.15. The TS interface, for the many places that hold an envelope
 * without needing a payload schema for it.
 */
export interface Envelope<T = unknown> {
  ns: typeof ENVELOPE_NS;
  target: EnvelopeTarget;
  /** See SPEC 5.16 / {@link MESSAGE_TYPES}. */
  type: string;
  /** uuid, echoed in the response. */
  reqId: string;
  payload: T;
}

/**
 * SPEC 5.15, runtime form. Zod schemas are not generic the way the interface
 * is, so the envelope is built per payload schema:
 * `envelopeSchema(ExecuteRequestSchema)`.
 */
export function envelopeSchema<T extends z.ZodType>(payload: T) {
  return z.object({
    ns: z.literal(ENVELOPE_NS),
    target: EnvelopeTargetSchema,
    type: z.string().min(1),
    reqId: z.string().min(1),
    payload,
  });
}

/** SPEC 5.15, the unvalidated envelope with an opaque payload. */
export const AnyEnvelopeSchema = envelopeSchema(z.unknown());

/**
 * SPEC 5.15 `[REQUIREMENT]`: every listener returns early if `msg?.ns !== "echo"`
 * or `msg.target` does not match its own role.
 *
 * `msg` arrives from a `chrome.runtime` listener as genuinely unknown data — it
 * may be null, a string, or a message from an unrelated extension — so nothing
 * about its shape is assumed before it is checked. The payload is *not*
 * validated here; the listener validates it with the schema for its own message
 * type.
 */
export function isEnvelopeFor<T = unknown>(
  msg: unknown,
  target: EnvelopeTarget
): msg is Envelope<T> {
  if (typeof msg !== "object" || msg === null) return false;
  const candidate = msg as Record<string, unknown>;
  return (
    candidate.ns === ENVELOPE_NS &&
    candidate.target === target &&
    typeof candidate.type === "string" &&
    typeof candidate.reqId === "string"
  );
}


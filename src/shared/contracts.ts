/**
 * SPEC 5.1 (`id`) and SPEC 7.6.1 rule 2. Element ids are generated by the
 * extension, never by the model, and are the only way an action names a target.
 */
export const ELEMENT_ID_PATTERN = /^el_\d{1,3}$/;

/** SPEC 5.1: `x` and `y` are document-relative, normalized to 0..1 (SPEC 12.6). */
const NormalizedCoordSchema = z.number().min(0).max(1);

/** SPEC 5.1: `role`, `tag`, and `inputType` are lowercase. */
const LowercaseNonEmptySchema = z
  .string()
  .min(1)
  .refine((s) => s === s.toLowerCase(), "must be lowercase");

/** SPEC 5.1: accessible names are truncated to 80 chars by the index builder. */
export const ELEMENT_NAME_MAX_CHARS = 80;

/** SPEC 5.1: element values are truncated to 40 chars. */
export const ELEMENT_VALUE_MAX_CHARS = 40;

/** SPEC 5.2: `document.title`, truncated to 120 chars. */
export const PAGE_TITLE_MAX_CHARS = 120;

/** SPEC 5.3: the normalized transcript handed to the resolver, max 200 chars. */
export const TRANSCRIPT_MAX_CHARS = 200;

/** SPEC 5.9: a spoken clarifying question, max 90 chars. */
export const CLARIFY_QUESTION_MAX_CHARS = 90;

/** SPEC 5.12: a stored page summary, max 1200 chars. */
export const SUMMARY_MAX_CHARS = 1200;

/** SPEC 5.14: the transcript copied into a telemetry record, max 120 chars. */
export const TELEMETRY_TRANSCRIPT_MAX_CHARS = 120;


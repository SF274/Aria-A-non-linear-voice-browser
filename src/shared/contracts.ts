/** SPEC 5.1. `name` and `value` are page-controlled and must pass through `sanitizeForPrompt()` (8.4) before any prompt. */
export const ElementIndexEntrySchema = z.object({
  /** "el_0".."el_N", assigned in index order, stable for one index build. */
  id: z.string().regex(ELEMENT_ID_PATTERN),
  /** ARIA role, explicit or implicit, lowercase (SPEC 12.3). */
  role: LowercaseNonEmptySchema,
  /** Accessible name, trimmed, newlines collapsed, truncated to 80 chars. */
  name: z.string().max(ELEMENT_NAME_MAX_CHARS),
  /** Normalized name used for matching (SPEC 7.2.1). */
  nameKey: z.string(),
  /** Document-relative horizontal centre, 0..1 (SPEC 12.6). */
  x: NormalizedCoordSchema,
  /** Document-relative vertical centre, 0..1 (SPEC 12.6). */
  y: NormalizedCoordSchema,
  /** False if disabled, aria-disabled="true", or readonly. */
  enabled: z.boolean(),
  /** SPEC 12.5. Only visible elements are indexed; always true, kept for forward compatibility. */
  visible: z.boolean(),
  /** True if the element's rect currently intersects the viewport. */
  inViewport: z.boolean(),
  /** Current value for input, textarea, select; null otherwise. Never populated for password fields. */
  value: z.string().max(ELEMENT_VALUE_MAX_CHARS).nullable(),
  /** Lowercase tagName, e.g. "button", "a", "input". */
  tag: LowercaseNonEmptySchema,
  /** input[type] lowercased, or null. */
  inputType: LowercaseNonEmptySchema.nullable(),
  /** True if input[type=password] (SPEC 8, R2.4). */
  isPassword: z.boolean(),
});

export type ElementIndexEntry = z.infer<typeof ElementIndexEntrySchema>;


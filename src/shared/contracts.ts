// 5.6 Verb, Action
// ---------------------------------------------------------------------------

/**
 * SPEC 5.6 / 5.5. The verb set is closed and contains no `navigate`:
 * navigation is only ever a side effect of clicking a real anchor that already
 * exists on the page, and the model cannot produce a URL (SPEC 8.3, R2.1).
 */
export const VERBS = [
  "click",
  "fill",
  "select",
  "check",
  "uncheck",
  "scrollTo",
  "focus",
] as const;

export const VerbSchema = z.enum(VERBS);

export type Verb = z.infer<typeof VerbSchema>;

/** SPEC 5.6 / 7.6.1 rule 6: `value` is present if and only if the verb is one of these. */
export const VALUE_REQUIRED_VERBS = ["fill", "select"] as const satisfies readonly Verb[];

function verbRequiresValue(verb: Verb): boolean {
  return (VALUE_REQUIRED_VERBS as readonly Verb[]).includes(verb);
}

/**
 * SPEC 5.6 (validated, internal). The `value` rule is enforced at runtime, not
 * only in the type: SPEC 7.6.1 rule 6 rejects an action whose `value` is
 * present for a verb that forbids it, or absent for one that requires it.
 */
export const ActionSchema = z
  .object({
    verb: VerbSchema,
    elementId: z.string(),
    /** Required for fill and select, forbidden otherwise. */
    value: z.string().optional(),
  })
  .superRefine((action, ctx) => {
    const requiresValue = verbRequiresValue(action.verb);
    if (requiresValue && action.value === undefined) {
      ctx.addIssue({
        code: "custom",
        path: ["value"],
        message: `value is required for verb "${action.verb}"`,
      });
    }
    if (!requiresValue && action.value !== undefined) {
      ctx.addIssue({
        code: "custom",
        path: ["value"],
        message: `value is forbidden for verb "${action.verb}"`,
      });
    }
  });

export type Action = z.infer<typeof ActionSchema>;

